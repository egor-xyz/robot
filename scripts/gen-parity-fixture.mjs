#!/usr/bin/env node
// Plays every random state of the real functions/crazy-robot through zsh and
// records what it prints, so claude-mod/robot.test.ts can hold the TypeScript
// twin to it (the test sandbox cannot run zsh itself).
// Usage: node scripts/gen-parity-fixture.mjs   (needs zsh)
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
// The states come from the zsh source itself, so the two cannot drift.
const STATES = readFileSync(join(root, 'functions', 'crazy-robot'), 'utf8')
  .match(/local -a states=\(([^)]*)\)/)[1]
  .trim()
  .split(/\s+/)
const DRAWS = 8
const POS = 5
const TRACK = 60
const TICKS = 24

// $2 state, $3 t, $4 pos, $5 dir, $6 mirror, $7 track, $8 seed. The first
// DRAWS $RANDOM values the seed gives are printed after the frame; the seed is
// then reset so crazy-robot consumes that same stream, and the TS side replays it.
const SCRIPT = `fpath=($1 $fpath); autoload -Uz crazy-robot
typeset _robot_state=$2 _robot_t=$3 _robot_dur=99999 _robot_pos=$4 _robot_dir=$5 _robot_mirror=$6 _robot_f _robot_s _robot_locked=0
RANDOM=$8; draws=(); repeat ${DRAWS} draws+=($RANDOM); RANDOM=$8
crazy-robot $7
print -rn -- $'\\x1f'"$draws"`

const cases = []
for (const state of STATES) {
  for (let t = 1; t <= TICKS; t++) {
    for (const mirror of [0, 1]) {
      const seed = 100 + t
      const stdout = execFileSync('zsh', [
        '-fc', SCRIPT, 'robot', join(root, 'functions'), state, String(t), String(POS), '1', String(mirror), String(TRACK), String(seed),
      ], { encoding: 'utf8' })
      const [out, draws] = stdout.split('\x1f')
      cases.push({ state, t, mirror, draws: draws.split(' ').map(Number), out })
    }
  }
}

// The ufo forest only grows on a wide track: the cow walks deep into the
// woods to the gap _robot_val picks.
const FOREST_POS = 60
const FOREST_TRACK = 100
const FOREST_SCRIPT = `fpath=($1 $fpath); autoload -Uz crazy-robot
typeset _robot_state=ufo _robot_t=$2 _robot_dur=999 _robot_pos=$3 _robot_dir=1 _robot_mirror=0 _robot_val=$4 _robot_f _robot_s _robot_locked=0
crazy-robot $5`
const forest = []
for (const value of [0, 1, 3]) {
  for (let t = 1; t < 80; t++) {
    const out = execFileSync('zsh', [
      '-fc', FOREST_SCRIPT, 'robot', join(root, 'functions'), String(t), String(FOREST_POS), String(value), String(FOREST_TRACK),
    ], { encoding: 'utf8' })
    forest.push({ t, value, out })
  }
}

// The ufo walk-in: from a pos short of room, t stays 0 while the robot steps right.
const WALK_IN_SCRIPT = `fpath=($1 $fpath); autoload -Uz crazy-robot
typeset _robot_state=ufo _robot_t=0 _robot_dur=999 _robot_pos=$2 _robot_dir=1 _robot_mirror=0 _robot_val=0 _robot_f _robot_s _robot_locked=0
RANDOM=$4; draws=(); repeat ${DRAWS} draws+=($RANDOM); RANDOM=$4
crazy-robot $3
print -rn -- $'\\x1f'"$draws"$'\\x1f'"$_robot_pos $_robot_t $_robot_val"`
const walkIn = []
for (const pos of [0, 9, 27, 28]) {
  const stdout = execFileSync('zsh', ['-fc', WALK_IN_SCRIPT, 'robot', join(root, 'functions'), String(pos), String(FOREST_TRACK), String(pos + 1)], { encoding: 'utf8' })
  const [out, draws, after] = stdout.split('\x1f')
  const [posAfter, tAfter, value] = after.split(' ').map(Number)
  walkIn.push({ pos, draws: draws.split(' ').map(Number), out, posAfter, tAfter, value })
}

const body = cases.map(c => `  ${JSON.stringify(c)},`).join('\n')
const forestBody = forest.map(c => `  ${JSON.stringify(c)},`).join('\n')
const walkInBody = walkIn.map(c => `  ${JSON.stringify(c)},`).join('\n')
writeFileSync(
  join(root, 'claude-mod', 'parity.fixture.ts'),
  `// Generated by scripts/gen-parity-fixture.mjs from the real functions/crazy-robot. Do not edit.
export const POS = ${POS}
export const TRACK = ${TRACK}

/** What zsh printed for one tick, and the $RANDOM stream it drew from. */
export const CASES: { state: string; t: number; mirror: 0 | 1; draws: number[]; out: string }[] = [
${body}
]

export const FOREST_POS = ${FOREST_POS}
export const FOREST_TRACK = ${FOREST_TRACK}

/** What zsh printed for one tick of the ufo scene in a deep forest, its gap picked by value. */
export const FOREST: { t: number; value: number; out: string }[] = [
${forestBody}
]

/** What zsh printed for tick 0 of the ufo scene from pos, on the forest track, and the state after. */
export const WALK_IN: { pos: number; draws: number[]; out: string; posAfter: number; tAfter: number; value: number }[] = [
${walkInBody}
]
`,
)
console.log(`wrote ${cases.length} cases, ${forest.length} forest cases`)
